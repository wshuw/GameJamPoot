using UnityEngine;
// Описывает урон одной конкретной атаки. Это данные АТАКУЮЩЕГО — при попадании
// они передаются цели, а дальше цель сама решает по своему состоянию
// (обычный удар / блок / парирование), что из этого применить. Живёт как поле
// на WeaponHitbox, поэтому у игрока и у каждого врага — свой набор цифр.
[System.Serializable]
public class AttackData
{
    [Header("Обычное попадание (цель без защиты)")]
    [Tooltip("ХП, которое теряет цель, если попадание пришлось не в блок и не в парирование")]
    public float hpDamage = 10f;
    [Tooltip("Стамина, которую получает цель при том же обычном попадании — " +
             "даже незащищённый удар немного заполняет шкалу стамины")]
    public float staminaDamageOnHit = 5f;

    [Header("Если цель блокирует")]
    [Tooltip("НЕ ИСПОЛЬЗУЕТСЯ. Блок сейчас = 0 урона по ХП всегда, " +
             "TakeDamage делает return до чтения этого поля. Оставлено про запас.")]
    public float chipDamageOnBlock = 2f;
    [Tooltip("СКОЛЬКО ДАМАГА ПО СТАМИНЕ ПОЛУЧИТ ОТ ТЕБЯ ТОТ КТО БЛОКИРУЕТ. " +
             "У ИГРОКА = 0, врагам пофиг от того что бьют в блок " +
             "Значение своё для каждого оружия: на оружии ВРАГА делаем БОЛЬШИМ " +
             "('блок бьёт по стамине игрока сильно'), на оружии ИГРОКА — МАЛЕНЬКИМ " +
             "('блокирование игрока бьёт по стамине врага немного').")]
    public float staminaDamageOnBlock = 20f;

    [Header("Если цель парирует")]
    [Tooltip("Своя стамина, которую получает ИГРОК за успешное парирование этой атаки " +
             "(с кэпом — см. parryStaminaCapFraction на PlayerHealth). " +
             "Работает ТОЛЬКО когда поле стоит на оружии ВРАГА: EnemyHealth это поле " +
             "не читает вообще — сам враг за своё парирование стамину себе не получает.")]
    public float staminaDamageOnParry = 8f;

    [Header("Если ЭТА атака была парирована (кем угодно)")]
    [Tooltip("Стамина, которую получает АТАКУЮЩИЙ (не тот, кто парировал!), когда его " +
             "атака была парирована — единственное поле, бьющее по нападавшему, а не " +
             "по защищавшемуся. На оружии ВРАГА: враг парируется игроком -> стамину " +
             "получает ВРАГ ('парируешь врага — побеждаешь'). На оружии ИГРОКА: игрок " +
             "парируется врагом -> стамину получает ИГРОК ('парирование игрока не " +
             "бьёт по стамине врага, но бьёт по стамине игрока').")]
    public float staminaDamageOnAttackerWhenParried = 15f;
}